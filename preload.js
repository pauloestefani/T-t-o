// Ponte segura entre o app (HTML) e o processo principal.
const { contextBridge, ipcRenderer, webUtils } = require("electron");

contextBridge.exposeInMainWorld("electronAPI", {
  isElectron: true,
  // transmissão de tela
  onPickSource: (cb) => ipcRenderer.on("pick-source", (_e, sources) => cb(sources)),
  pickSource: (id) => ipcRenderer.send("source-picked", id),
  setShareOptions: (o) => ipcRenderer.send("share:opts", o),
  // memória de configs
  getSettings: () => ipcRenderer.invoke("settings:get"),
  saveSettings: (o) => ipcRenderer.invoke("settings:set", o),
  // servidor embutido
  startServer: (port) => ipcRenderer.invoke("server:start", port),
  stopServer: () => ipcRenderer.invoke("server:stop"),
  // rede LAN
  lanInfo: () => ipcRenderer.invoke("lan:info"),
  lanListen: () => ipcRenderer.invoke("lan:listen"),
  lanProbe: (ip) => ipcRenderer.invoke("lan:probe", ip),
  lanStart: (o) => ipcRenderer.invoke("lan:start", o),
  lanStop: () => ipcRenderer.invoke("lan:stop"),
  lanElevate: (r) => ipcRenderer.invoke("lan:elevate", r),
  lanWrite: (u8) => ipcRenderer.send("lan:out", u8),
  onLanIn: (cb) => ipcRenderer.on("lan:in", (_e, d) => cb(d)),
  onLanStatus: (cb) => ipcRenderer.on("lan:status", (_e, d) => cb(d)),
  onMcWorld: (cb) => ipcRenderer.on("lan:mcworld", (_e, d) => cb(d)),
  mcWatch: (on) => ipcRenderer.send("mc:watch", !!on),
  tunListen: (key, port) => ipcRenderer.invoke("tun:listen", key, port),
  tunUnlisten: (key) => ipcRenderer.invoke("tun:unlisten", key),
  tunConnect: (port) => ipcRenderer.invoke("tun:connect", port),
  tunWrite: (id, u8) => ipcRenderer.send("tun:write", id, u8),
  tunPause: (id, on) => ipcRenderer.send("tun:pause", id, !!on),
  tunEnd: (id) => ipcRenderer.send("tun:end", id),
  onTunIncoming: (cb) => ipcRenderer.on("tun:incoming", (_e, key, id) => cb(key, id)),
  onTunData: (cb) => ipcRenderer.on("tun:data", (_e, id, d) => cb(id, d)),
  onTunClose: (cb) => ipcRenderer.on("tun:close", (_e, id) => cb(id)),
  onLanResume: (cb) => ipcRenderer.on("lan:resume", (_e, d) => cb(d)),
  // auto-update
  onUpdateAvailable: (cb) => ipcRenderer.on("update-available", (_e, d) => cb(d)),
  onUpdateProgress: (cb) => ipcRenderer.on("update-progress", (_e, p) => cb(p)),
  onUpdateReady: (cb) => ipcRenderer.on("update-ready", (_e, d) => cb(d)),
  onUpdateError: (cb) => ipcRenderer.on("update-error", (_e, d) => cb(d)),
  onUpdateStatus: (cb) => ipcRenderer.on("update-status", (_e, d) => cb(d)),
  checkUpdate: () => ipcRenderer.invoke("update:check"),
  applyUpdate: (dir) => ipcRenderer.invoke("update:apply", dir),
  openExternal: (url) => ipcRenderer.invoke("open:external", url),
  ytTitle: (id) => ipcRenderer.invoke("yt:title", id),
  setThemeBg: (c) => ipcRenderer.send("theme:bg", c),
  setWindowMode: (o) => ipcRenderer.send("win:mode", o),
  appReady: () => ipcRenderer.send("app:ready"),
  isAdmin: () => ipcRenderer.invoke("app:isAdmin"),
  fileOpen: (o) => ipcRenderer.invoke("file:open", o),
  fileWriteAt: (id, pos, u8) => ipcRenderer.send("file:writeAt", id, pos, u8),
  fileClose: (id, ok) => ipcRenderer.invoke("file:close", id, ok),
  fileShow: (p) => ipcRenderer.invoke("file:show", p),
  fileOpenPath: (p) => ipcRenderer.invoke("file:open-path", p),
  fileFolder: () => ipcRenderer.invoke("file:folder"),
  fileGetDir: () => ipcRenderer.invoke("file:getDir"),
  filePickDir: () => ipcRenderer.invoke("file:pickDir"),
  fileResetDir: () => ipcRenderer.invoke("file:resetDir"),
  // só arquivos de verdade escolhidos pela pessoa têm caminho (um File criado pela página não tem)
  fileReg: (file) => { let p = ""; try { p = webUtils.getPathForFile(file); } catch (_) {} return p ? ipcRenderer.invoke("file:reg", p) : Promise.resolve(null); },
  fileRead: (sid, pos, len) => ipcRenderer.invoke("file:read", sid, pos, len),
  fileUnshare: (sid) => ipcRenderer.invoke("file:unshare", sid),
  libAdd: (o) => ipcRenderer.invoke("lib:add", o),
  libList: (key) => ipcRenderer.invoke("lib:list", key),
  libHashes: (root) => ipcRenderer.invoke("lib:hashes", root),
  libRemove: (key, root, kind) => ipcRenderer.invoke("lib:remove", key, root, kind),
  libKeys: () => ipcRenderer.invoke("lib:keys"),
  idGet: () => ipcRenderer.invoke("id:get"),
  idSign: (txt) => ipcRenderer.invoke("id:sign", txt),
  attention: () => ipcRenderer.send("win:attention"),
  setAlwaysAdmin: (on) => ipcRenderer.invoke("app:setAlwaysAdmin", on),
  elevate: () => ipcRenderer.invoke("app:elevate"),
  musicResolve: (url) => ipcRenderer.invoke("music:resolve", url),
  musicSearch: (o) => ipcRenderer.invoke("music:search", o),
  musicKeyInfo: () => ipcRenderer.invoke("music:keyInfo"),
  musicTestKey: (k) => ipcRenderer.invoke("music:testKey", k),
  pcAudioAvailable: () => ipcRenderer.invoke("pcaudio:available"),
  pcAudioList: () => ipcRenderer.invoke("pcaudio:list"),
  pcAudioStart: (o) => ipcRenderer.invoke("pcaudio:start", o),
  pcAudioStop: (id) => ipcRenderer.invoke("pcaudio:stop", id),
  onPcAudioData: (cb) => ipcRenderer.on("pcaudio:data", (_e, id, d) => cb(id, d)),
  onPcAudioEnd: (cb) => ipcRenderer.on("pcaudio:end", (_e, d) => cb(d))
});
